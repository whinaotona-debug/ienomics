function ensureRoot() {
  let el = document.getElementById('ie-tour-root');
  if (!el) {
    el = document.createElement('div');
    el.id = 'ie-tour-root';
    document.body.appendChild(el);
  }
  return el;
}

function findTarget(name) {
  if (!name) return null;
  return document.querySelector(`[data-tour="${name}"]`);
}

